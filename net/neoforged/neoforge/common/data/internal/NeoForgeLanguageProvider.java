   private <T> void addColored(TagKey<T> baseTagKey, String pattern) {
      for (DyeColor color : DyeColor.values()) {
         TagKey<T> coloredTag = TagKey.create(
            baseTagKey.registry(),
            ResourceLocation.fromNamespaceAndPath(
               baseTagKey.location().getNamespace(), baseTagKey.location().getPath() + "/" + color.name().toLowerCase(Locale.ROOT)
            )
         );
         this.add(coloredTag, pattern.replace("{color}", StringUtils.capitalize(color.getName())));
      }
   }

